#!/usr/bin/env python3.12
"""Generate the codec tables behind `rust/src/smtp/header.rs`'s
`bytes.decode(charset)` (the `_encoded_words.decode` step of CPython's email
header parser).

Run from the repository root, under the pinned CPython 3.12.14, with that
interpreter's own source tree:

    python3.12 rust/tools/gen_smtp_codec_tables.py /opt/zeropw-tools/cpython rust/src/smtp/header

It (re)writes three files, all committed (nothing is generated at build time):

* `codecs.rs` -- `encodings.aliases.aliases`, every importable `encodings`
  module and how the port decodes it, and each charmap codec's
  `decoding_table` (read from the running interpreter).
* `cjk_tables.rs` -- the decode maps of `Modules/cjkcodecs` (`mappings_*.h`,
  parsed from the C source the interpreter was built from) and the small
  Hangul tables of `_codecs_kr.c`, for the faithful ports of the
  `_multibytecodec` decoders in `cjk.rs`.
* `unicode_tables.rs` -- the Unicode name database `\\N{...}` escapes look
  up (`Modules/unicodename_db.h`: every name the `code_hash` lookup can
  find, and the name aliases), the RFC 3454 `stringprep` tables nameprep
  uses (brute-forced through `stringprep` itself), and the Unicode 3.2.0
  NFKC data of `unicodedata.ucd_3_2_0.normalize` (per-character NFKD from
  the interpreter, canonical combining classes from the current database,
  and the composition pairs of `Modules/unicodedata_db.h`).

The script asserts the invariants the Rust readers rely on (for example that
no decode-map value is ASCII, so `?` can stand for an unmapped cell).
"""

import codecs
import importlib
import os
import re
import stringprep
import sys
import unicodedata

assert sys.version_info[:3] == (3, 12, 14), sys.version
SRC, OUT = sys.argv[1], sys.argv[2]
UCD32 = unicodedata.ucd_3_2_0


def read(rel):
    with open(os.path.join(SRC, rel), encoding="latin-1") as f:
        return f.read()


def c_array_body(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", text, re.S)
    assert m, name
    return re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)


def c_ints(text, name, consts=None):
    consts = consts or {}
    out = []
    for tok in c_array_body(text, name).replace("\n", "").split(","):
        tok = tok.strip()
        if not tok:
            continue
        out.append(consts[tok] if tok in consts else int(tok, 0))
    return out


def rust_str(s, wrap=72):
    """A Rust string literal for `s`, wrapped with `\\` line continuations.
    Printable characters (Python's `str.isprintable`) are written as-is,
    everything else as `\\u{...}`."""
    parts = []
    for ch in s:
        if ch in '"\\':
            parts.append("\\" + ch)
        elif ch.isprintable() and ch != "　":
            parts.append(ch)
        else:
            parts.append("\\u{%x}" % ord(ch))
    lines, line, width = [], [], 0
    for p in parts:
        # A `\` line continuation also skips the next line's leading
        # whitespace, so never wrap before a space.
        if width >= wrap and not p[0].isspace():
            lines.append("".join(line))
            line, width = [], 0
        line.append(p)
        width += 1
    lines.append("".join(line))
    return '"' + "\\\n    ".join(lines) + '"'


