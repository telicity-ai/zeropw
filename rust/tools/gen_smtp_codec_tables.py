def gen_codecs():
    import encodings.aliases

    names = sorted(
        f[:-3] for f in os.listdir(os.path.dirname(encodings.aliases.__file__))
        if f.endswith(".py") and f not in ("__init__.py", "aliases.py")
    )
    modules, charmaps = [], []
    for name in names:
        try:
            mod = importlib.import_module("encodings." + name)
        except ImportError:
            continue  # mbcs, oem: Windows only
        info = mod.getregentry()
        if not info._is_text_encoding:
            modules.append((name, "Codec::NonText"))
        elif hasattr(mod, "decoding_table"):
            table = [ord(c) for c in mod.decoding_table]
            assert len(table) == 256 and all(c <= 0xFFFF for c in table), name
            modules.append((name, "Codec::Charmap(%d)" % len(charmaps)))
            charmaps.append((name, table))
        elif name in CJK:
            modules.append((name, "Codec::Cjk(Cjk::%s)" % CJK[name]))
        else:
            modules.append((name, FIXED[name]))
    out = [HEADER.format(what="`encodings` package: module list, `encodings.aliases.aliases`, "
                         "charmap `decoding_table`s")]
    out.append("use super::Codec;\nuse super::cjk::Cjk;\nuse super::unicodec::Endian;\n\n")
    out.append("/// `encodings.aliases.aliases`: normalized alias -> codec module.\n")
    out.append("#[rustfmt::skip]\npub(super) const ALIASES: &[(&str, &str)] = &[\n")
    for k, v in sorted(encodings.aliases.aliases.items()):
        out.append('    ("%s", "%s"),\n' % (k, v))
    out.append("];\n\n")
    out.append("/// Importable `encodings.<module>` codec modules and how this port decodes them.\n")
    out.append("#[rustfmt::skip]\npub(super) const MODULES: &[(&str, Codec)] = &[\n")
    for k, v in modules:
        out.append('    ("%s", %s),\n' % (k, v))
    out.append("];\n\n")
    out.append("/// Each charmap codec's `decoding_table`; `0xFFFE` is an undefined byte.\n")
    out.append("#[rustfmt::skip]\npub(super) const CHARMAPS: &[[u16; 256]] = &[\n")
    for name, table in charmaps:
        out.append("    // %s\n    [\n" % name)
        for i in range(0, 256, 16):
            out.append("        " + " ".join("0x%04X," % c for c in table[i:i + 16]) + "\n")
        out.append("    ],\n")
    out.append("];\n")
    return "".join(out)


# ----------------------------------------------------------- cjk_tables.rs

UCS2_MAPS = [
    ("mappings_cn.h", "gb2312"), ("mappings_cn.h", "gbkext"), ("mappings_cn.h", "gb18030ext"),
    ("mappings_kr.h", "ksx1001"), ("mappings_kr.h", "cp949ext"),
    ("mappings_tw.h", "big5"), ("mappings_tw.h", "cp950ext"),
    ("mappings_hk.h", "big5hkscs"),
    ("mappings_jp.h", "jisx0208"), ("mappings_jp.h", "jisx0212"), ("mappings_jp.h", "cp932ext"),
    ("mappings_jp.h", "jisx0213_1_bmp"), ("mappings_jp.h", "jisx0213_2_bmp"),
    ("mappings_jp.h", "jisx0213_1_emp"), ("mappings_jp.h", "jisx0213_2_emp"),
]
CJK_DIR = "Modules/cjkcodecs/"


def parse_index(text, name):
    body = c_array_body(text, name + "_decmap")
    entries = re.findall(r"\{\s*(0|__\w+\+\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", body.replace("\n", ""))
    assert len(entries) == 256, (name, len(entries))
    out = []
    for ptr, bottom, top in entries:
        bottom, top = int(bottom), int(top)
        if ptr == "0":
            out.append(None)
        else:
            base, off = ptr.split("+")
            assert base == "__" + name + "_decmap", ptr
            assert bottom <= top, (name, bottom, top)
            out.append((int(off), bottom, top))
    return out


def index_rust(index):
    cells = []
    for e in index:
        # A NULL map row becomes an empty range (bottom > top).
        cells.append("(%d, %d, %d)," % ((0, 1, 0) if e is None else e))
    lines = ["        " + " ".join(cells[i:i + 8]) for i in range(0, 256, 8)]
    return "[\n" + "\n".join(lines) + "\n    ]"


def gen_cjk():
    out = [HEADER.format(what="`Modules/cjkcodecs/mappings_*.h` decode maps and the "
                         "`_codecs_kr.c` Hangul tables")]
    out.append("""
use super::cjk::{DecodeMap, WideDecodeMap};
use std::sync::OnceLock;

// Each `DecodeMap` is CPython's `struct dbcs_index` array for one charset:
// per lead byte `(offset, bottom, top)` into the 16-bit cells, which are the
// characters of `data`: `?` stands for `UNIINV` (0xFFFE, an unmapped cell), a
// character in plane 15 (U+F0000 + v) for a cell value v that is ASCII, a
// surrogate or 0xFFFF, and any other character for its own code point.  A
// NULL row is `(0, 1, 0)`.
""")
    uniinv = 0xFFFE
    for header, name in UCS2_MAPS:
        text = read(CJK_DIR + header)
        cells = c_ints(text, "__%s_decmap" % name, {"U": uniinv})
        index = parse_index(text, name)
        for e in index:
            if e is not None:
                assert e[0] + e[2] - e[1] < len(cells), name
        chars = []
        for c in cells:
            assert 0 <= c <= 0xFFFF, (name, c)
            if c == uniinv:
                chars.append("?")
            elif c >= 0x80 and not 0xD800 <= c <= 0xDFFF and c != 0xFFFF:
                chars.append(chr(c))
            else:
                # ASCII, a surrogate or 0xFFFF (big5hkscs and the *_emp maps
                # hold the low 16 bits of a supplementary code point).
                chars.append(chr(0xF0000 + c))
        out.append("\n/// `%s_decmap` (`%s`).\n#[rustfmt::skip]\n" % (name, header))
        out.append("pub(super) static %s: DecodeMap = DecodeMap {\n    index: &%s,\n" % (
            name.upper(), index_rust(index)))
        out.append("    data: %s,\n    cells: OnceLock::new(),\n};\n" % rust_str("".join(chars)))
    # jisx0213_pair: Py_UCS4 cells (two code points packed as hi << 16 | lo).
    text = read(CJK_DIR + "mappings_jisx0213_pair.h")
    cells = c_ints(text, "__jisx0213_pair_decmap", {"U": uniinv})
    index = parse_index(text, "jisx0213_pair")
    out.append("\n/// `jisx0213_pair_decmap` (`mappings_jisx0213_pair.h`): `hi << 16 | lo`.\n")
    out.append("#[rustfmt::skip]\npub(super) static JISX0213_PAIR: WideDecodeMap = WideDecodeMap {\n")
    out.append("    index: &%s,\n    cells: &[\n" % index_rust(index))
    for i in range(0, len(cells), 6):
        out.append("        " + " ".join("0x%08X," % c for c in cells[i:i + 6]) + "\n")
    out.append("    ],\n};\n")
    # gb18030 BMP ranges.
    text = read(CJK_DIR + "mappings_cn.h")
    body = c_array_body(text, "gb18030_to_unibmp_ranges").replace("\n", "")
    ranges = [tuple(int(x) for x in m) for m in re.findall(r"\{(\d+),(\d+),(\d+)\}", body)]
    assert ranges[-1][:2] == (0, 0) and ranges[-1][2] == 39420, ranges[-1]
    out.append("\n/// `gb18030_to_unibmp_ranges` (`mappings_cn.h`): `(first, last, base)`, \n")
    out.append("/// ending with the `{0, 0, 39420}` sentinel.\n#[rustfmt::skip]\n")
    out.append("pub(super) const GB18030_TO_UNIBMP_RANGES: &[(u32, u32, u32)] = &[\n")
    for i in range(0, len(ranges), 4):
        out.append("    " + " ".join("(%d, %d, %d)," % r for r in ranges[i:i + 4]) + "\n")
    out.append("];\n")
    # big5hkscs plane hints.
    text = read(CJK_DIR + "mappings_hk.h")
    hk_index = parse_index(text, "big5hkscs")
    bh2s = lambda c1, c2: (c1 - 0x87) * (0xFE - 0x40 + 1) + (c2 - 0x40)
    hints = {}
    for hint in ("big5hkscs_phint_0", "big5hkscs_phint_12130", "big5hkscs_phint_21924"):
        hints[hint] = c_ints(text, hint)
        out.append("\n/// `%s` (`mappings_hk.h`).\n#[rustfmt::skip]\n" % hint)
        out.append("pub(super) const %s: &[u8] = &[\n" % hint.upper())
        data = hints[hint]
        for i in range(0, len(data), 20):
            out.append("    " + " ".join("%d," % b for b in data[i:i + 20]) + "\n")
        out.append("];\n")
    hk_cells = c_ints(text, "__big5hkscs_decmap", {"U": uniinv})
    for c1, e in enumerate(hk_index):
        if e is None:
            continue
        off, bottom, top = e
        for c2 in range(bottom, top + 1):
            if hk_cells[off + c2 - bottom] == uniinv:
                continue
            s = bh2s(c1, c2)
            if bh2s(0x87, 0x40) <= s <= bh2s(0xA0, 0xFE):
                s, h = s - bh2s(0x87, 0x40), hints["big5hkscs_phint_0"]
            elif bh2s(0xC6, 0xA1) <= s <= bh2s(0xC8, 0xFE):
                s, h = s - bh2s(0xC6, 0xA1), hints["big5hkscs_phint_12130"]
            elif bh2s(0xF9, 0xD6) <= s <= bh2s(0xFE, 0xFE):
                s, h = s - bh2s(0xF9, 0xD6), hints["big5hkscs_phint_21924"]
            else:
                raise AssertionError("big5hkscs cell outside the hint planes: %x %x" % (c1, c2))
            assert (s >> 3) < len(h), (c1, c2)
    # _codecs_kr.c Hangul tables.
    text = read(CJK_DIR + "_codecs_kr.c")
    for name, consts in (
        ("cgk2u_choseong", {"NONE": 127}), ("cgk2u_jongseong", {"NONE": 127}),
        ("johabidx_choseong", {"NONE": 0xFF, "FILL": 0xFD}),
        ("johabidx_jungseong", {"NONE": 0xFF, "FILL": 0xFD}),
        ("johabidx_jongseong", {"NONE": 0xFF, "FILL": 0xFD}),
        ("johabjamo_choseong", {"NONE": 0xFF, "FILL": 0xFD}),
        ("johabjamo_jungseong", {"NONE": 0xFF, "FILL": 0xFD}),
        ("johabjamo_jongseong", {"NONE": 0xFF, "FILL": 0xFD}),
    ):
        data = c_ints(text, name, consts)
        out.append("\n/// `%s` (`_codecs_kr.c`).\n#[rustfmt::skip]\n" % name)
        out.append("pub(super) const %s: [u8; %d] = [\n" % (name.upper(), len(data)))
        for i in range(0, len(data), 16):
            out.append("    " + " ".join("0x%02X," % b for b in data[i:i + 16]) + "\n")
        out.append("];\n")
    return "".join(out)


# ------------------------------------------------------- unicode_tables.rs

def leb128(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def ranges_of(pred, top=0x10FFFF):
    out, start = [], None
    for cp in range(top + 2):
        inside = cp <= top and pred(cp)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def ranges_rust(name, doc, ranges):
    out = ["\n/// %s\n#[rustfmt::skip]\npub(super) const %s: &[(u32, u32)] = &[\n" % (doc, name)]
    for i in range(0, len(ranges), 6):
        out.append("    " + " ".join("(0x%X, 0x%X)," % r for r in ranges[i:i + 6]) + "\n")
    out.append("];\n")
    return "".join(out)


def gen_names():
    text = read("Modules/unicodename_db.h")
    lexicon = c_ints(text, "lexicon")
    lexicon_offset = c_ints(text, "lexicon_offset")
    phrasebook = c_ints(text, "phrasebook")
    offset1 = c_ints(text, "phrasebook_offset1")
    offset2 = c_ints(text, "phrasebook_offset2")
    code_hash = c_ints(text, "code_hash")
    name_aliases = c_ints(text, "name_aliases")
    shift = int(re.search(r"#define phrasebook_shift (\d+)", text).group(1))
    short = int(re.search(r"#define phrasebook_short (\d+)", text).group(1))
    aliases_start = int(re.search(r"aliases_start = (0x[0-9a-f]+);", text).group(1), 16)
    aliases_end = int(re.search(r"aliases_end = (0x[0-9a-f]+);", text).group(1), 16)
    seq_start = int(re.search(r"named_sequences_start = (0x[0-9a-f]+);", text).group(1), 16)
    seq_end = int(re.search(r"named_sequences_end = (0x[0-9a-f]+);", text).group(1), 16)
    assert len(name_aliases) == aliases_end - aliases_start

    def is_unified_ideograph(code):
        return any(lo <= code <= hi for lo, hi in CJK_RANGES)

    def getucname(code):
        # `_getucname(NULL, code, ..., with_alias_and_seq=1)`.
        if 0xAC00 <= code < 0xAC00 + 11172:
            return None  # algorithmic: never in `code_hash` (checked below)
        if is_unified_ideograph(code):
            return None
        off = offset1[code >> shift]
        off = offset2[(off << shift) + (code & ((1 << shift) - 1))]
        if not off:
            return None
        words = []
        while True:
            word = phrasebook[off] - short
            if word >= 0:
                word = (word << 8) + phrasebook[off + 1]
                off += 2
            else:
                word = phrasebook[off]
                off += 1
            w = lexicon_offset[word]
            chars = []
            while lexicon[w] < 128:
                chars.append(chr(lexicon[w]))
                w += 1
            chars.append(chr(lexicon[w] & 127))
            words.append("".join(chars))
            if lexicon[w] == 128:
                break
        # The buffer joins words with ' '; the terminating 0x80 adds a NUL.
        name = " ".join(words)
        assert name.endswith("\0"), name
        return name[:-1]

    src = read("Modules/unicodedata.c")
    CJK_RANGES[:] = [
        (int(a, 16), int(b, 16))
        for a, b in re.findall(r"\(0x([0-9A-F]+) <= code && code <= 0x([0-9A-F]+)\)", src)
    ]
    assert len(CJK_RANGES) == 9, CJK_RANGES

    names, aliases, seen = {}, [], set()
    for v in code_hash:
        if not v:
            continue
        name = getucname(v)
        assert name is not None and name not in seen, (hex(v), name)
        seen.add(name)
        assert name == name.upper() and all(0x20 <= ord(c) < 0x7F for c in name), name
        if aliases_start <= v < aliases_end:
            aliases.append((name, name_aliases[v - aliases_start]))
        elif seq_start <= v < seq_end:
            continue  # `_check_alias_and_seq(..., with_named_seq=0)` rejects it
        else:
            assert unicodedata.name(chr(v)) == name, hex(v)
            names[v] = name
    # Every named code point is reachable through the hash.
    for cp in range(0x110000):
        n = unicodedata.name(chr(cp), None)
        if n is None or 0xAC00 <= cp < 0xAC00 + 11172 or n.startswith("CJK UNIFIED IDEOGRAPH-"):
            continue
        assert names.get(cp) == n, (hex(cp), n)
    for name, target in aliases:
        assert unicodedata.lookup(name) == chr(target), name

    freq = {}
    for name in names.values():
        for w in name.split(" "):
            freq[w] = freq.get(w, 0) + 1
    words = sorted(freq, key=lambda w: (-freq[w], w))
    assert all(w and " " not in w for w in words)
    word_id = {w: i for i, w in enumerate(words)}
    stream = bytearray()
    prev_cp, prev_words = -1, []
    for cp in sorted(names):
        ws = names[cp].split(" ")
        shared = 0
        while shared < min(len(ws), len(prev_words)) and ws[shared] == prev_words[shared]:
            shared += 1
        gap, fresh = cp - prev_cp - 1, len(ws) - shared
        if gap == 0 and shared < 15 and fresh < 16:
            stream.append(shared << 4 | fresh)
        else:
            stream += b"\xff" + leb128(gap) + leb128(shared) + leb128(fresh)
        for w in ws[shared:]:
            stream += leb128(word_id[w])
        prev_cp, prev_words = cp, ws
    import base64
    b64 = base64.b64encode(bytes(stream)).decode()

    out = ["""
/// Unicode %s name lookup (`_getcode(NULL, name, len, &code, 0)` of
/// `Modules/unicodedata.c`, as `\\\\N{...}` escapes use it).
///
/// `NAME_WORDS` lists every word of the names `code_hash` holds, most
/// frequent first.  `NAME_DATA` is base64 of a byte stream with one record
/// per named code point in ascending order.  A record starts with a header:
/// one byte `shared << 4 | fresh` when the code point follows the previous
/// one directly, or `0xFF` and three LEB128 numbers (the gap to the previous
/// code point minus one, `shared`, `fresh`).  `shared` is how many leading
/// words the name has in common with the previous name; the `fresh` words
/// that follow are LEB128 indices into `NAME_WORDS`.  Hangul syllables
/// and CJK unified ideographs are algorithmic and not listed; named
/// sequences are not listed because a `\\\\N{...}` lookup rejects them.
pub(super) const NAME_COUNT: usize = %d;
""" % (unicodedata.unidata_version, len(names))]
    out.append("\n/// The words of `NAME_DATA`, space separated.\n#[rustfmt::skip]\n")
    out.append("pub(super) const NAME_WORDS: &str = %s;\n" % rust_str(" ".join(words), 96))
    out.append("\n/// See [`NAME_COUNT`].\n#[rustfmt::skip]\n")
    out.append("pub(super) const NAME_DATA: &str = %s;\n" % rust_str(b64, 96))
    out.append("\n/// `name_aliases`: alias name -> code point (`unicodename_db.h`).\n")
    out.append("#[rustfmt::skip]\npub(super) const NAME_ALIASES: &[(&str, u32)] = &[\n")
    for name, target in sorted(aliases):
        out.append('    ("%s", 0x%04X),\n' % (name, target))
    out.append("];\n")
    out.append("\n/// `is_unified_ideograph` (`Modules/unicodedata.c`).\n#[rustfmt::skip]\n")
    out.append("pub(super) const CJK_UNIFIED_IDEOGRAPHS: &[(u32, u32)] = &[\n")
    for lo, hi in CJK_RANGES:
        out.append("    (0x%X, 0x%X),\n" % (lo, hi))
    out.append("];\n")
    return "".join(out)


