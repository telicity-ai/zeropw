def gen_nameprep():
    out = []
    b1 = sorted(stringprep.b1_set)
    assert all(stringprep.in_table_b1(chr(c)) == (c in stringprep.b1_set) for c in range(0x110000))
    out.append("\n/// `stringprep.in_table_b1` (map to nothing).\n#[rustfmt::skip]\n")
    out.append("pub(super) const STRINGPREP_B1: &[u32] = &[%s];\n" % ", ".join("0x%X" % c for c in b1))
    maps = []
    for cp in range(0x110000):
        c = chr(cp)
        if cp in stringprep.b1_set:
            continue
        m = stringprep.map_table_b2(c)
        if m != c:
            assert all(not 0xD800 <= ord(x) <= 0xDFFF for x in m)
            maps.append((cp, m))
    out.append("\n/// `stringprep.map_table_b2` where it is not the identity.\n#[rustfmt::skip]\n")
    out.append("pub(super) const STRINGPREP_B2: &[(u32, &str)] = &[\n")
    for cp, m in maps:
        out.append("    (0x%X, %s),\n" % (cp, rust_str(m)))
    out.append("];\n")

    def prohibited(cp):
        c = chr(cp)
        return (stringprep.in_table_c12(c) or stringprep.in_table_c22(c)
                or stringprep.in_table_c3(c) or stringprep.in_table_c4(c)
                or stringprep.in_table_c5(c) or stringprep.in_table_c6(c)
                or stringprep.in_table_c7(c) or stringprep.in_table_c8(c)
                or stringprep.in_table_c9(c))

    out.append(ranges_rust("STRINGPREP_PROHIBITED",
                           "`in_table_c12` .. `in_table_c9` as `nameprep` checks them.",
                           ranges_of(prohibited)))
    out.append(ranges_rust("STRINGPREP_D1", "`stringprep.in_table_d1` (RandALCat).",
                           ranges_of(lambda cp: stringprep.in_table_d1(chr(cp)))))
    out.append(ranges_rust("STRINGPREP_D2", "`stringprep.in_table_d2` (LCat).",
                           ranges_of(lambda cp: stringprep.in_table_d2(chr(cp)))))
    return "".join(out)


def gen_nfkc():
    out = []
    decomp = []
    for cp in range(0x110000):
        if 0xAC00 <= cp < 0xAC00 + 11172:
            continue  # Hangul: algorithmic in `nfd_nfkd`
        d = UCD32.normalize("NFKD", chr(cp))
        if d != chr(cp):
            assert all(not 0xD800 <= ord(x) <= 0xDFFF for x in d)
            decomp.append((cp, d))
    out.append("""
/// `unicodedata.ucd_3_2_0.normalize("NFKD", chr(c))` where it is not `chr(c)`
/// (Hangul syllables excepted): each character's full compatibility
/// decomposition under Unicode 3.2.0 (`get_decomp_record` with the 3.2.0
/// unassigned check and `normalization_3_2_0` corrections), already in
/// canonical order.
#[rustfmt::skip]
pub(super) const NFKD_3_2_0: &[(u32, &str)] = &[
""")
    for cp, d in decomp:
        out.append("    (0x%X, %s),\n" % (cp, rust_str(d)))
    out.append("];\n")
    ccc = []
    start = None
    for cp in range(0x110001):
        v = unicodedata.combining(chr(cp)) if cp < 0x110000 else 0
        if start is not None and v != start[1]:
            if start[1]:
                ccc.append((start[0], cp - 1, start[1]))
            start = None
        if start is None and v:
            start = (cp, v)
    out.append("\n/// `_getrecord_ex(c)->combining` (the current database, %s, even for\n" %
               unicodedata.unidata_version)
    out.append("/// `ucd_3_2_0`): `(first, last, class)` for every non-zero class.\n#[rustfmt::skip]\n")
    out.append("pub(super) const COMBINING: &[(u32, u32, u8)] = &[\n")
    for i in range(0, len(ccc), 5):
        out.append("    " + " ".join("(0x%X, 0x%X, %d)," % r for r in ccc[i:i + 5]) + "\n")
    out.append("];\n")
    # Composition pairs (`nfc_first`/`nfc_last`/`comp_index`/`comp_data`).
    text = read("Modules/unicodedata_db.h")
    total_last = int(re.search(r"#define TOTAL_LAST (\d+)", text).group(1))
    comp_shift = int(re.search(r"#define COMP_SHIFT (\d+)", text).group(1))
    comp_index = c_ints(text, "comp_index")
    comp_data = c_ints(text, "comp_data")

    def reindex(name):
        body = c_array_body(text, name)
        out = {}
        for start, count, index in re.findall(r"\{\s*(\d+),\s*(\d+),\s*(\d+)\}", body):
            start, count, index = int(start), int(count), int(index)
            if start == 0:
                break
            for d in range(count + 1):
                out[start + d] = index + d
        return out

    first, last = reindex("nfc_first"), reindex("nfc_last")
    pairs = []
    for f, fi in first.items():
        for l, li in last.items():
            index = fi * total_last + li
            code = comp_data[(comp_index[index >> comp_shift] << comp_shift)
                             + (index & ((1 << comp_shift) - 1))]
            if code:
                pairs.append((f, l, code))
    pairs.sort()
    out.append("\n/// `nfc_first` x `nfc_last` -> `comp_data` (`unicodedata_db.h`, %s):\n" %
               unicodedata.unidata_version)
    out.append("/// `(first, last, composite)`, sorted.\n#[rustfmt::skip]\n")
    out.append("pub(super) const COMPOSITIONS: &[(u32, u32, u32)] = &[\n")
    for i in range(0, len(pairs), 4):
        out.append("    " + " ".join("(0x%X, 0x%X, 0x%X)," % p for p in pairs[i:i + 4]) + "\n")
    out.append("];\n")
    return "".join(out)


